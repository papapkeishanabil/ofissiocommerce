export function colorNameKey(name: string) {
  return name.normalize("NFKC").trim().replace(/\s+/g, " ").toLocaleLowerCase("id-ID");
}
const byName = new Map<string, (typeof PRODUCT_COLOR_MASTER)[number]>();
for (const color of PRODUCT_COLOR_MASTER) {
  const key = colorNameKey(color.name);
  if (byName.has(key)) throw new Error(`Duplicate master color: ${color.name}`);
  byName.set(key, color);
}
export function masterColor(name: string) { return byName.get(colorNameKey(name)); }
