import assert from "node:assert/strict";
import { PRODUCT_MOCK_DATA } from "../src/features/products/product.mock-data";
import { productSearchDescription, productSearchMetadata, productSearchName, productSearchSnippet } from "../src/features/seo/product-metadata";

const fixture = PRODUCT_MOCK_DATA[0];
assert.ok(fixture);
const product = { ...fixture, source: "woocommerce" as const, name: "Kemeja Kerja KT-001", slug: "kemeja-kerja-teknisi-kt-001", material: "American Drill", supports_embroidery: true };
const metadata = productSearchMetadata(product);
assert.deepEqual(metadata.title, { absolute: "Kemeja Kerja Teknisi KT-001 | Ofissio" });
assert.equal(metadata.openGraph?.title, "Kemeja Kerja Teknisi KT-001 | Ofissio");
assert.equal(metadata.twitter?.description, metadata.description);
assert.equal(metadata.alternates?.canonical, "https://ofissio.com/product/kemeja-kerja-teknisi-kt-001");
assert.ok(String(metadata.description).includes("American Drill"));
assert.ok(String(metadata.description).includes("teknisi"));
assert.ok(!String(metadata.description).includes("ready stock"));
assert.equal(productSearchName({ ...product, name: "Nama Baru Admin" }), "Nama Baru Admin");
assert.equal(productSearchName({ ...product, slug: "kemeja-kerja-kt-001" }), "Kemeja Kerja Teknisi KT-001");
assert.equal(productSearchMetadata({ ...product, slug: "kemeja-kerja-kt-001" }).alternates?.canonical, "https://ofissio.com/product/kemeja-kerja-kt-001");
assert.deepEqual(productSearchMetadata({ ...product, name: "Kemeja Ofissio KT-001" }).title, { absolute: "Kemeja Ofissio KT-001" });
assert.deepEqual(productSearchMetadata({ ...product, source: "mock" }).robots, { index: false, follow: false });
const firstSentence = "Kemeja ini memiliki saku dan pilihan ukuran untuk kebutuhan tim operasional.";
assert.equal(productSearchSnippet(firstSentence + " " + "Rincian tambahan tersedia pada produk. ".repeat(10)), firstSentence + " Rincian tambahan tersedia pada produk. Rincian tambahan tersedia pada produk.");
const long = productSearchSnippet("kemeja kerja lapangan dengan detail fungsional ".repeat(10));
assert.ok(long.length <= 170 && long.endsWith("…"));
assert.equal(productSearchSnippet("<p>Kemeja\\nkerja</p>"), "Kemeja kerja");
const noDetails = { ...product, slug: "model-lain", name: "Model Lain", short_description: "", description: "Deskripsi produk belum tersedia.", material: "Material belum diisi", supports_embroidery: false };
assert.ok(!productSearchDescription(noDetails).includes("belum diisi"));
assert.ok(!productSearchDescription(noDetails).includes("bordir"));
const safety = { ...product, name: "Kemeja Safety KS-003", slug: "kemeja-safety-ks-003", category: "Kemeja Safety", short_description: "Kemeja safety dengan pita reflektif." };
assert.equal(productSearchDescription(safety), "Kemeja Safety KS-003 dengan pita reflektif.");
assert.equal(productSearchDescription({ ...safety, short_description: "Deskripsi khusus dari admin." }), "Deskripsi khusus dari admin.");
console.log("PASS: product metadata, factual snippets, complete sentences, custom copy, branding, canonical and mock noindex");
