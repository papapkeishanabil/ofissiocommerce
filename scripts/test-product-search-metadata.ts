import assert from "node:assert/strict";
import { PRODUCT_MOCK_DATA } from "../src/features/products/product.mock-data";
import { productSearchMetadata, productSearchName, productSearchSnippet } from "../src/features/seo/product-metadata";
const product = { ...PRODUCT_MOCK_DATA[0]!, source: "woocommerce" as const, name: "Kemeja Lapangan KL-007", slug: "kl-007", seoInput: { name: "Kemeja Lapangan KL-007", modelCode: "KL-007", description: "", materials: ["Baby Canvas"], colors: ["Camel"], sleeves: ["long"] } };
const metadata = productSearchMetadata(product);
assert.deepEqual(metadata.title, { absolute: "Kemeja Lapangan Baby Canvas Camel KL-007 | OFISSIO" });
assert.equal(metadata.openGraph?.title, "Kemeja Lapangan Baby Canvas Camel KL-007 | OFISSIO");
assert.equal(metadata.twitter?.description, metadata.description);
assert.equal(metadata.alternates?.canonical, "https://ofissio.com/product/kl-007");
assert.equal(metadata.keywords, null);
assert.deepEqual(productSearchMetadata({ ...product, source: "mock" }).robots, { index: false, follow: false });
assert.equal(productSearchName({ name: "Nama Baru Admin", slug: "model-baru" }), "Nama Baru Admin");
const manual = productSearchMetadata({ ...product, seo: { title: "Judul khusus dari tim", description: "Deskripsi khusus dari tim." } });
assert.deepEqual(manual.title, { absolute: "Judul khusus dari tim" });
assert.equal(manual.description, "Deskripsi khusus dari tim.");
assert.equal(manual.openGraph?.description, manual.description);
assert.equal(manual.alternates?.canonical, metadata.alternates?.canonical);
assert.deepEqual(productSearchMetadata({ ...product, seo: { title: " ", description: " " } }).title, metadata.title);
assert.equal(productSearchSnippet("<p>Kemeja\\nkerja</p>"), "Kemeja kerja");
assert.ok(productSearchSnippet("kemeja kerja lapangan dengan detail fungsional ".repeat(10)).length <= 170);
console.log("PASS: factual automatic product metadata, manual/reset, OG/Twitter parity, canonical and mock noindex.");
